import { defineConfig } from 'vite'
import fs from 'node:fs'
import path from 'node:path'

// Find all example folders
const examplesDir = path.resolve(import.meta.dirname, 'examples')
const exampleFolders = fs
  .readdirSync(examplesDir)
  .filter(
    (folder) =>
      fs.statSync(path.join(examplesDir, folder)).isDirectory() &&
      fs.existsSync(path.join(examplesDir, folder, 'index.html')),
  )
  .sort()

function exampleLinks(folders: string[]) {
  return folders
    .map((folder) => {
      const label = folder.replace(/^v5-/, '').replaceAll('-', ' ')
      const badge = folder.startsWith('v5-spike-')
        ? '\n              <span class="badge">Phase 0 prototype</span>'
        : ''
      return `          <li>
            <a href="/examples/${folder}/">
              <span>${label}</span>${badge}
            </a>
          </li>`
    })
    .join('\n')
}

const v5Examples = exampleFolders.filter((folder) => folder.startsWith('v5-'))
const v4Examples = exampleFolders.filter((folder) => !folder.startsWith('v5-'))

// Generate an index.html file with links
const indexHtmlContent = `<!-- Auto generated by npm run build-examples -->
<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <title>FEWS Charts | Examples</title>
    <link rel="stylesheet" href="/examples/shared/gallery.css" />
  </head>
  <body>
    <header class="page-header">
      <p class="eyebrow">Deltares / FEWS Web OC Charts</p>
      <h1>Chart examples</h1>
      <p>Explore chart types, shared state and interactions across library versions.</p>
      <nav aria-label="Library versions">
        <a href="#v5">v5 examples</a>
        <a href="#v4">v4 examples</a>
      </nav>
    </header>
    <main>
      <section id="v5" aria-labelledby="v5-heading">
        <div class="section-heading">
          <h2 id="v5-heading">v5 <span class="badge">In development</span></h2>
          <span class="example-count">${v5Examples.length} examples</span>
        </div>
        <p>
          New functional API: named scales, shared domains, runtime options and lifecycle. Phase 0
          prototypes are labelled separately and do not use the public v5 API.
        </p>
        <ul class="example-grid">
${exampleLinks(v5Examples)}
        </ul>
      </section>
      <section id="v4" aria-labelledby="v4-heading">
        <div class="section-heading">
          <h2 id="v4-heading">v4 <span class="badge">Current release</span></h2>
          <span class="example-count">${v4Examples.length} examples</span>
        </div>
        <p>Established class-based API: chart types, axes, overlays and interactions.</p>
        <ul class="example-grid">
${exampleLinks(v4Examples)}
        </ul>
      </section>
    </main>
    <footer>Examples run locally against the library source.</footer>
  </body>
</html>
`

const isDev = process.env.NODE_ENV === 'development'

// Ensure the dist directory exists
const distDir = isDev ? path.resolve(import.meta.dirname, 'dist') : import.meta.dirname

if (isDev && !fs.existsSync(distDir)) {
  fs.mkdirSync(distDir)
}

// Write the generated index.html to the dist folder during development
fs.writeFileSync(path.resolve(distDir, 'index.html'), indexHtmlContent)

// Define Vite build inputs
const inputEntries: Record<string, string> = {
  main: path.resolve(distDir, 'index.html'), // Auto-generated main index
}

// Add each example folder's index.html as an entry point
exampleFolders.forEach((folder) => {
  inputEntries[folder] = path.join(examplesDir, folder, 'index.html')
})

export default defineConfig({
  plugins: [
    {
      name: 'redirect-home',
      configureServer(server) {
        server.middlewares.use((req, res, next) => {
          if (req.url === '/') {
            res.writeHead(302, { Location: '/dist/index.html' })
            res.end()
          } else {
            next()
          }
        })
      },
    },
  ],
  build: {
    rolldownOptions: {
      input: inputEntries,
    },
  },
  resolve: {
    alias: {
      '@lib': path.resolve(import.meta.dirname, './src'),
      '@shared': path.resolve(import.meta.dirname, './examples/shared'),
    },
  },
})
